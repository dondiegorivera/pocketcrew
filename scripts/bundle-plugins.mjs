#!/usr/bin/env node
// pocketcrew.config.ts → src/plugins.gen.ts: static imports of the enabled plugins' manifests, so the Worker bundles them.
// Runs first before check, test and deploy (then the skill and role bundlers, which add the plugins' skills and roles).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { enabledPlugins, ROOT } from "./plugins.mjs";

const plugins = await enabledPlugins();
const id = (name) => name.replace(/[^a-zA-Z0-9]/g, "_");
// Written before the manifests load: they import core, and core imports this file (a fresh clone has none yet). A
// refused build puts the previous one back.
const GEN = join(ROOT, "src", "plugins.gen.ts");
const previous = existsSync(GEN) ? readFileSync(GEN, "utf8") : undefined;
writeFileSync(
	GEN,
	[
		"// Generated by scripts/bundle-plugins.mjs from pocketcrew.config.ts. Do not edit: enable plugins there.",
		'import type { Plugin } from "./plugin.ts";',
		...plugins.map((p) => `import ${id(p.name)} from "../plugins/${p.name}/plugin.ts";`),
		"",
		"/** The enabled plugins. A function: called after every module has loaded, never while they load (src/lazy.ts). */",
		`export const plugins = (): Plugin<any>[] => [${plugins.map((p) => id(p.name)).join(", ")}];`,
		"",
	].join("\n"),
);
// What only the files can tell: a plugin that adds agents brings its section of the crew skill and their roles.
const problems = [];
for (const p of plugins) {
	const { default: m } = await import(join(p.dir, "plugin.ts"));
	if (m.name !== p.name) problems.push(`plugins/${p.name}/plugin.ts calls itself "${m.name}"`);
	for (const r of m.requires ?? []) if (!plugins.some((x) => x.name === r)) problems.push(`plugins/${p.name} needs the ${r} plugin: enable it too`);
	const agents = Object.keys(m.agents ?? {});
	if (agents.length && !existsSync(join(p.dir, "skill.md"))) problems.push(`plugins/${p.name} adds agents but no skill.md (its section of the crew skill)`);
	for (const a of agents) if (!existsSync(join(p.dir, "roles", `${a}.md`))) problems.push(`plugins/${p.name}: no roles/${a}.md`);
	for (const s of m.server ?? []) if (!existsSync(join(p.dir, s.file))) problems.push(`plugins/${p.name}: server step ${s.file} is missing`);
}
if (problems.length) {
	if (previous !== undefined) writeFileSync(GEN, previous);
	console.error(`Plugins not bundled:\n${problems.join("\n")}`);
	process.exit(1);
}
console.log(`bundled ${plugins.length} plugin${plugins.length === 1 ? "" : "s"}: ${plugins.map((p) => p.name).join(", ") || "none"}`);
