#!/usr/bin/env node
// Bundles skills/<name>/SKILL.md (and any other .md or .txt files in the folder, as reference files), and the enabled
// plugins' skills (plugins/<plugin>/skills/), into src/skills.gen.ts, which the Worker imports. The crew skill gets
// each enabled plugin's section (plugins/<plugin>/skill.md) where it says <!-- plugins -->. Runs before check, test and
// deploy (npm pre-scripts); fails on a bad skill.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MAX_FILE_CHARS, parseSkill } from "../src/skill-format.ts";
import { enabledPlugins, ROOT } from "./plugins.mjs";

const OUT = join(ROOT, "src", "skills.gen.ts");
const plugins = await enabledPlugins();
const DIRS = [join(ROOT, "skills"), ...plugins.map((p) => join(p.dir, "skills")).filter(existsSync)];
const folders = DIRS.flatMap((dir) => readdirSync(dir).sort().map((folder) => [dir, folder]));
const pluginSections = plugins.map((p) => join(p.dir, "skill.md")).filter(existsSync).map((f) => readFileSync(f, "utf8").trim());

const skills = [];
const problems = [];
for (const [DIR, folder] of folders) {
	const path = join(DIR, folder);
	if (!statSync(path).isDirectory()) continue;
	let text = readFileSync(join(path, "SKILL.md"), "utf8");
	if (folder === "crew") text = text.replace("<!-- plugins -->", pluginSections.join("\n"));
	const parsed = parseSkill(text);
	if (typeof parsed === "string") problems.push(`${folder}: ${parsed}`);
	else if (parsed.name !== folder) problems.push(`${folder}: the folder and the name in SKILL.md differ (${parsed.name})`);
	else {
		const files = {};
		for (const f of readdirSync(path).sort()) {
			if (f === "SKILL.md" || !/\.(md|txt)$/.test(f)) continue;
			const text = readFileSync(join(path, f), "utf8");
			if (text.length > MAX_FILE_CHARS) problems.push(`${folder}/${f}: over ${MAX_FILE_CHARS} characters`);
			files[f] = text;
		}
		skills.push({ ...parsed, files, source: "repo" });
	}
}
if (problems.length) {
	console.error(`Skills not bundled:\n${problems.join("\n")}`);
	process.exit(1);
}
writeFileSync(
	OUT,
	`// Generated by scripts/bundle-skills.mjs from skills/. Do not edit: change the skill and run npm run check.\nimport type { Skill } from "./skill-format.ts";\n\nexport const BUNDLED_SKILLS: Skill[] = ${JSON.stringify(skills, null, "\t")};\n`,
);
console.log(`bundled ${skills.length} skill${skills.length === 1 ? "" : "s"}: ${skills.map((s) => s.name).join(", ")}`);
